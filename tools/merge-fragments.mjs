#!/usr/bin/env node
// Parallel agents never write the shared ledgers directly. Each agent writes its own fragment:
//   plan/fragments/<AGENT-ID>/needs-owner.md | needs-operator.md | decisions.md | blocked.md
// This script regenerates NEEDS-OWNER.md, NEEDS-OPERATOR.md, plan/DECISIONS.md and plan/BLOCKED.md
// from all fragments (idempotent), and merges images/generated/*.json into images/GENERATED.json.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { abs } from './lib.mjs';

const TARGETS = {
  'needs-owner.md': ['NEEDS-OWNER.md', '# Needs the owner (Will Fraley)\n\nQuestions only the owner can answer. Each names the page and placeholder it affects.\n'],
  'needs-operator.md': ['NEEDS-OPERATOR.md', '# Needs the operator (Quinn)\n\nThings only the operator can do.\n'],
  'decisions.md': ['plan/DECISIONS.md', '# Decisions\n\nEvery call made without asking, with its reason. Newest stage last.\n'],
  'blocked.md': ['plan/BLOCKED.md', '# Blocked\n\nGate failures that survived 3 retries, and what was done instead.\n'],
};
const NAMES = {};
const base = abs('plan/fragments');
const agents = fs.existsSync(base) ? fs.readdirSync(base).filter((d) => fs.statSync(path.join(base, d)).isDirectory()).sort() : [];
for (const [frag, [target, header]] of Object.entries(TARGETS)) {
  const parts = [];
  for (const ag of agents) {
    const f = path.join(base, ag, frag);
    if (!fs.existsSync(f)) continue;
    const body = fs.readFileSync(f, 'utf8').trim();
    if (body) parts.push(`## ${ag}\n\n${body}\n`);
  }
  if (!parts.length && !fs.existsSync(abs(target)) && frag === 'blocked.md') continue;
  fs.mkdirSync(path.dirname(abs(target)), { recursive: true });
  fs.writeFileSync(abs(target), `${header}\n<!-- generated by tools/merge-fragments.mjs from plan/fragments/*/${frag} — edit the fragments, not this file -->\n\n${parts.join('\n') || '_None yet._\n'}`);
  NAMES[target] = parts.length;
}
if (fs.existsSync(abs('images/generated'))) execFileSync('node', [abs('tools/images.mjs'), '--merge'], { stdio: 'inherit' });
console.log('merged:', JSON.stringify(NAMES));
